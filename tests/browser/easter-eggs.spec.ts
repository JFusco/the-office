test('Shift-modified phrases are ignored and clear partial secrets', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('[data-scene-label="agent"]').first()).toBeVisible();
  const office = page.getByRole('region', { name: 'Interactive isometric office' });
  await page.keyboard.down('Shift');
  for (const key of 'DANCE THE OFFICE') await page.keyboard.press(key === ' ' ? 'Space' : key);
  await page.keyboard.up('Shift');
  await expect(office).toHaveAttribute('data-party', 'idle');
  await expect(office).toHaveAttribute('data-office-cast', 'original');
  await page.keyboard.type('dan');
  await page.keyboard.press('Shift+C');
  await page.keyboard.type('e');
  await expect(office).toHaveAttribute('data-party', 'idle');
  await page.keyboard.press('Escape');
  await page.keyboard.type('the offi');
  await page.keyboard.press('Shift+C');
  await page.keyboard.type('e');
  await expect(office).toHaveAttribute('data-office-cast', 'original');
  await page.keyboard.press('Escape');
  expect(await page.evaluate(() => Array.from('DANCE THE OFFICE', key => window.dispatchEvent(new KeyboardEvent('keydown', { key, shiftKey: true, cancelable: true, bubbles: true }))))).toEqual(Array(16).fill(true));
  await page.keyboard.type('dance');
  await expect(office).toHaveAttribute('data-party', 'active');
  await page.keyboard.type('the office');
  await expect(office).toHaveAttribute('data-office-cast', 'sitcom');
});

