import { afterEach, expect, test, vi } from 'vitest';
import { Store } from '../../server/store';
import { Engine } from '../../server/engine';
import { Coordinator, coordination } from '../../server/coordination';
import { completeNativeCheckpoint } from '../../server/brain-checkpoint';
import { projectById } from '../../server/projects';
import type { DailyCheckpoint, MaintenanceRun } from '../../src/shared';
const stores: Store[] = [];
afterEach(() => stores.splice(0).forEach(store => store.close()));
function setup() {
    const store = new Store(':memory:', projectById('brain')); stores.push(store);
    store.state.coordination = coordination();
    const checkpoint: DailyCheckpoint = { id: 'checkpoint', date: '2026-10-29', dueAt: '2026-10-29T21:00:00Z', requestedAt: '', startedAt: '', endedAt: 'old-end', status: 'blocked', runId: 'original', detail: 'Original worker exited with surviving subprocesses' };
    const original: MaintenanceRun = { id: 'original', checkpointId: checkpoint.id, requestedAt: '', startedAt: '', endedAt: '', status: 'reconciled', weekly: false, stage: 'brain-maintenance', error: '', steps: [{ role: 'pm', stage: 'maintenance-readback', at: '', result: { outcome: 'passed', summary: 'No uncertain effects remain', ledger: 'Keep older failures and pending captures', blocker: '', candidates: [], receipts: [{ id: 'readback', action: 'read', target: 'original', verified: true, uncertain: false, detail: 'Native claim refused completed; no write dispatched' }] } }] };
    const wrapper: MaintenanceRun = { ...original, id: 'earlier-completed-wrapper', status: 'completed', nativeRunId: 'b3dca6de-3de6-4a6c-96c8-4c21ac9747c2', steps: [] };
    store.state.maintenance = { runs: [wrapper, original], lastDaily: '2026-10-29', lastWeekly: '', ledger: 'Keep historical failures' };
    store.state.coordination.checkpoints.push(checkpoint);
    const gate = { slotDate: '2026-10-29', attempts: 1, retryAfter: null, active: null, completed: { id: wrapper.nativeRunId!, authorId: 'c2453dce-7399-4e8b-9dd6-1090cd798c52', slotDate: '2026-10-29', phase: 'completed' as const, completedAt: '2026-10-29T14:01:47Z', reportSha256: 'a'.repeat(64) } };
    return { store, checkpoint, original, wrapper, gate };
}
test('scheduler-owned retry reads an already completed native date once without dispatching work', async () => {
    const a = setup(), engine = new Engine(a.store), coordinator = new Coordinator(a.store, engine);
    const read = vi.spyOn(engine.maintenance as any, 'readStatus').mockResolvedValue(a.gate);
    const worker = vi.spyOn(engine.agents, 'run');
    const request = vi.spyOn(engine.maintenance, 'request');
    const previous = JSON.parse(JSON.stringify(a.original.steps));
    await coordinator.retryCheckpoint(a.checkpoint.id);
    expect(read).toHaveBeenCalledTimes(1); expect(worker).not.toHaveBeenCalled(); expect(request).not.toHaveBeenCalled();
    expect(a.checkpoint).toMatchObject({ status: 'completed', runId: a.original.id });
    expect(a.original.status).toBe('reconciled'); expect(a.original.steps.slice(0, -1)).toEqual(previous);
    const receipt = JSON.parse(a.original.steps.at(-1)!.result.receipts[0].detail);
    expect(receipt).toMatchObject({ originalRunId: 'original', native: { id: a.gate.completed.id }, prior: { status: 'blocked', detail: 'Original worker exited with surviving subprocesses', endedAt: 'old-end' } });
    expect(a.store.state.maintenance!.ledger).toBe('Keep historical failures'); expect(a.gate.attempts).toBe(1);
    expect(completeNativeCheckpoint(a.store, a.checkpoint, a.original, a.gate)).toBe(false);
    expect(a.original.steps).toHaveLength(2);
});
test.each(['blocked', 'interrupted'] as const)('automatic recovery of a %s run refuses native completion', async status => {
    const a = setup(), engine = new Engine(a.store), coordinator = new Coordinator(a.store, engine);
    a.original.status = status;
    a.original.error = 'Native claim refused an already completed date';
    a.original.readbackRetry = { attempts: 2, nextAt: '', history: [], exhausted: false };
    const reconcile = vi.spyOn(engine.maintenance, 'reconcile').mockImplementation(async () => { a.original.status = 'reconciled'; return a.original; });
    const read = vi.spyOn(engine.maintenance as any, 'readStatus').mockResolvedValue(a.gate);
    const worker = vi.spyOn(engine.agents, 'run'), request = vi.spyOn(engine.maintenance, 'request');
    const previous = structuredClone(a.checkpoint), steps = structuredClone(a.original.steps);
    await coordinator.pump({ kind: 'recovery', id: a.original.id });
    expect(reconcile).toHaveBeenCalledWith(a.original.id); expect(read).toHaveBeenCalledTimes(1);
    expect(a.checkpoint).toEqual(previous); expect(a.original.steps).toEqual(steps);
    expect(a.original.status).toBe('reconciled'); expect(a.original.readbackRetry.exhausted).toBe(true);
    expect(a.store.state.events).toContainEqual(expect.objectContaining({ kind: 'maintenance-recovery-followup', message: expect.stringContaining('Brain has active work, a completed date, or its daily retry limit') }));
    expect(a.store.state.events.some(event => ['checkpoint-native-reconciled', 'maintenance-recovery-finished'].includes(event.kind))).toBe(false);
    expect(worker).not.toHaveBeenCalled(); expect(request).not.toHaveBeenCalled();
});
test.each(['active', 'wrong-date', 'missing-report', 'missing-wrapper', 'uncertain-readback', 'stopping-worker', 'repair-continuation', 'paused'] as const)('native checkpoint remains stopped with %s evidence', scenario => {
    const a = setup();
    if (scenario === 'active') (a.gate as any).active = a.gate.completed;
    if (scenario === 'wrong-date') a.gate.completed.slotDate = '2026-10-28';
    if (scenario === 'missing-report') a.gate.completed.reportSha256 = '';
    if (scenario === 'missing-wrapper') a.wrapper.nativeRunId = '';
    if (scenario === 'uncertain-readback') a.original.steps[0].result.receipts[0].uncertain = true;
    if (scenario === 'stopping-worker') a.store.state.workLog = [{ id: 'stopping', requestId: a.original.id, status: 'stopping' } as any];
    if (scenario === 'repair-continuation') a.checkpoint.continuationId = 'existing-repair';
    if (scenario === 'paused') a.store.state.paused = true;
    const before = JSON.stringify(a.store.state);
    expect(completeNativeCheckpoint(a.store, a.checkpoint, a.original, a.gate)).toBe(false);
    expect(JSON.stringify(a.store.state)).toBe(before);
});
test('legacy completed wrapper requires its exact native author continuation identity', () => {
    const a = setup(); a.wrapper.nativeRunId = '';
    const continuation: any = { id: 'legacy', runId: a.wrapper.id, status: 'completed', nativeRunId: a.gate.completed.id, nativeAuthorId: 'different-author' };
    a.store.state.coordination!.continuations = [continuation];
    expect(completeNativeCheckpoint(a.store, a.checkpoint, a.original, a.gate)).toBe(false);
    continuation.nativeAuthorId = a.gate.completed.authorId;
    expect(completeNativeCheckpoint(a.store, a.checkpoint, a.original, a.gate)).toBe(true);
});
test('the automatic completion read-back route is idempotent and never retries an uncompleted native date', async () => {
    const a = setup(), engine = new Engine(a.store), coordinator = new Coordinator(a.store, engine);
    const read = vi.spyOn(engine.maintenance as any, 'readStatus').mockResolvedValue(a.gate);
    const request = vi.spyOn(engine.maintenance, 'request');
    await coordinator.readBackCheckpoint(a.checkpoint.id);
    await coordinator.readBackCheckpoint(a.checkpoint.id);
    expect(read).toHaveBeenCalledTimes(1); expect(a.original.steps).toHaveLength(2); expect(request).not.toHaveBeenCalled();
    a.checkpoint.status = 'blocked'; (a.gate as any).completed = null;
    await expect(coordinator.readBackCheckpoint(a.checkpoint.id)).rejects.toThrow('no maintenance retry');
    expect(a.checkpoint.status).toBe('blocked'); expect(request).not.toHaveBeenCalled();
});
