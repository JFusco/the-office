import { afterEach, expect, test, vi } from 'vitest';
import { mkdtempSync, mkdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { Store } from '../../server/store';
import { Engine } from '../../server/engine';
import { GitHubDelivery } from '../../server/github-delivery';
import { adoptCandidate } from '../../server/candidate-adoption';
import { projectById } from '../../server/projects';
import { coordination } from '../../server/coordination';
const roots: string[] = [], stores: Store[] = [];
afterEach(() => { stores.splice(0).forEach(store => store.close()); roots.splice(0).forEach(root => rmSync(root, { recursive: true, force: true })); });
test('saved delivery output is adopted on the same head and scope defects queue a focused repair', async () => {
    const root = mkdtempSync(resolve(tmpdir(), 'office-adoption-'));
    roots.push(root);
    const repo = resolve(root, 'primary'), worktree = resolve(root, 'candidate');
    mkdirSync(repo);
    mkdirSync(worktree);
    const store = new Store(':memory:', { ...projectById('cms-field-vocabulary'), repo });
    stores.push(store);
    store.state.coordination = coordination();
    const engine = new Engine(store), head = '8d1ea2bd935e53ac512244901da47b66d9b10933';
    const job: any = { id: 'saved-job', key: 'GH-91', status: 'blocked', stage: 'implement', head: '', worktree: '', branch: '', steps: [{ stage: 'implement', result: { commit: head, worktree, branch: 'owned-91', summary: 'Saved proposal', receipts: [], findings: [{ id: 'f-lock-acceptance', status: 'open' }] } }] };
    store.state.coordination.jobs = [job];
    engine.maintenance.verifyCandidate = vi.fn(async () => { });
    const run = vi.fn(async () => ({ allowed: false, repairable: true, summary: 'Remove lock acceptance on existing candidate', findings: [{ id: 'f-lock-acceptance', status: 'open' }], preservedDispositions: 0, heldProfiles: [], followups: [] }) as any);
    engine.agents.run = run;
    const execute: any = async (_program: string, args: string[]) => args[0] === 'rev-parse' ? (args[1] === '--show-toplevel' ? worktree : head) : args[0] === 'status' ? '' : args[0] === 'merge-base' ? 'a'.repeat(40) : args.includes('--name-only') ? 'sources.lock.json' : 'Saved scoped diff';
    const delivery = new GitHubDelivery(store, engine, execute);
    await expect(adoptCandidate(delivery, 'GH-91', { complete: false, fresh: false, ownership: { status: 'clear' } })).rejects.toThrow('ownership');
    expect(run).not.toHaveBeenCalled();
    await adoptCandidate(delivery, 'GH-91', { complete: true, fresh: true, ownership: { status: 'clear' } });
    expect(job).toMatchObject({ head, worktree, branch: 'owned-91', stage: 'scope-repair', status: 'queued', candidateRecovery: { head, findingIds: ['f-lock-acceptance'] } });
    expect(job.steps[0].result.findings[0].status).toBe('open');
    expect(run).toHaveBeenCalledTimes(1);
});
