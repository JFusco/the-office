// Bundles the maintained launcher modules in scripts/overseer-launcher/ into the one file the
// installer copies, scripts/overseer-launch.mjs, with the repository's own Vite. A maintainer's
// step: the bundle is committed with its sources, and a unit test requires the two to agree.
// The candidate release never produces it. See docs/overseer.md, Launcher.
//
//   pnpm build:overseer-launcher
import { writeFileSync } from 'node:fs';
import { isBuiltin } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT = fileURLToPath(import.meta.url);
export const REPOSITORY = resolve(dirname(SCRIPT), '..');
export const LAUNCHER_ENTRY = resolve(REPOSITORY, 'scripts/overseer-launcher/launch.mjs');
export const LAUNCHER_BUNDLE = resolve(REPOSITORY, 'scripts/overseer-launch.mjs');
export const BANNER = '// Generated by pnpm build:overseer-launcher from scripts/overseer-launcher/. Do not edit.';

const builtin = specifier => specifier.startsWith('node:') && isBuiltin(specifier);

/**
 * The one entry chunk a build produced, or an error naming what else it held: another chunk, an
 * asset, or an import of anything but an actual `node:` built-in.
 */
export function launcherChunk(result) {
    const outputs = (Array.isArray(result) ? result : [result]).flatMap(build => build?.output ?? []);
    const chunks = outputs.filter(item => item.type === 'chunk'), assets = outputs.filter(item => item.type !== 'chunk');
    if (assets.length) throw new Error(`the launcher build produced assets: ${assets.map(item => item.fileName).join(', ')}`);
    if (chunks.length !== 1 || !chunks[0].isEntry || chunks[0].fileName !== 'overseer-launch.mjs' || chunks[0].facadeModuleId !== LAUNCHER_ENTRY)
        throw new Error(`the launcher build must produce exactly one entry chunk for launch.mjs, not: ${chunks.map(item => item.fileName).join(', ') || 'none'}`);
    const [chunk] = chunks, foreign = [...chunk.imports, ...chunk.dynamicImports].filter(specifier => !builtin(specifier));
    if (foreign.length) throw new Error(`the launcher bundle imports more than Node built-ins: ${foreign.join(', ')}`);
    return chunk.code.startsWith(BANNER) ? chunk.code : `${BANNER}\n${chunk.code}`;
}

/** The bundle's text, built in memory from the maintained modules; nothing is written. */
export async function bundleLauncher() {
    const { build } = await import('vite');
    const result = await build({
        root: REPOSITORY, configFile: false, envFile: false, mode: 'production', logLevel: 'silent', publicDir: false,
        ssr: { target: 'node' },
        build: {
            ssr: LAUNCHER_ENTRY, target: 'node24', write: false, copyPublicDir: false, minify: false, sourcemap: false, emptyOutDir: false,
            rollupOptions: { output: { format: 'es', entryFileNames: 'overseer-launch.mjs', inlineDynamicImports: true, banner: BANNER } },
        },
    });
    return launcherChunk(result);
}

if (process.argv[1] && resolve(process.argv[1]) === SCRIPT) {
    try { writeFileSync(LAUNCHER_BUNDLE, await bundleLauncher(), 'utf8'); console.log(`wrote ${LAUNCHER_BUNDLE}`); }
    catch (error) { console.error(`The launcher was not bundled: ${error instanceof Error ? error.message : String(error)}`); process.exitCode = 1; }
}
